<script setup>
// Every DNS record: what labdex generates, and what each DNS server holds, side by side.
import FilterSelect from '../components/FilterSelect.vue'
import { computed, ref, watch } from 'vue'
import Pager from '../components/Pager.vue'
import { useQuery } from '../query'
import { toast } from '../store'

const query = useQuery('/api/dns', { staleMs: 30000, onError: (e) => toast(e.message, 'error') })
const d = computed(() => query.data.value)
const loading = computed(() => query.loading.value && !d.value)
const tab = ref('')
const servers = computed(() => d.value?.servers || [])
watch(d, (v) => { if (v && !tab.value) tab.value = v.servers.length ? v.servers[0].integration : 'generated' }, { immediate: true })
const q = ref('')
const status = ref('')
const zone = ref('')
const page = ref(0)
const SIZE = 50
watch([q, status, zone, tab], () => { page.value = 0 })

const STATUS = {
  'in sync': ['ok', 'in sync'], missing: ['warn', 'missing: the next sync creates it'],
  stale: ['warn', 'stale: labdex made it, the next sync deletes it'], unmanaged: ['', 'unmanaged: made by hand or by something else'],
}
const server = computed(() => servers.value.find((s) => s.integration === tab.value))
const rows = computed(() => (tab.value === 'generated' ? d.value?.generated || [] : server.value?.records || []))
const zones = computed(() => [...new Set(rows.value.map((r) => r.zone).filter(Boolean))].sort())
const counts = computed(() => {
  const c = {}
  for (const r of server.value?.records || []) c[r.status] = (c[r.status] || 0) + 1
  return c
})
const filtered = computed(() => {
  const n = q.value.trim().toLowerCase()
  return rows.value.filter((r) => (!status.value || r.status === status.value) && (!zone.value || r.zone === zone.value) &&
    (!n || `${r.name} ${r.type} ${r.value} ${r.host || ''}`.toLowerCase().includes(n)))
})
const paged = computed(() => filtered.value.slice(page.value * SIZE, (page.value + 1) * SIZE))
</script>

<template>
  <div class="page">
    <div class="page-head">
      <h1>DNS</h1>
      <span class="sub">{{ d ? `${d.generated.length} generated records in ${d.zones.length} zone${d.zones.length === 1 ? '' : 's'}` : '' }}</span>
      <span class="grow"></span>
      <input v-model="q" type="search" placeholder="Search names, values, hosts" style="max-width: 300px" aria-label="Search records">
      <button class="btn small" :disabled="query.loading.value" @click="query.refresh()">Refresh</button>
    </div>
    <p v-if="loading" class="faint">Asking the DNS servers …</p>
    <template v-else-if="d">
      <nav class="tabs">
        <a v-for="s in servers" :key="s.integration" href="#" :class="{ 'router-link-active': tab === s.integration }" @click.prevent="tab = s.integration; status = ''">
          {{ s.integration }} <span class="faint">{{ s.plugin }}</span></a>
        <a href="#" :class="{ 'router-link-active': tab === 'generated' }" @click.prevent="tab = 'generated'; status = ''">Generated by labdex</a>
      </nav>
      <div v-if="server?.error" class="errbox" style="margin-bottom: 14px">{{ server.integration }}: {{ server.error }}</div>
      <div class="filters">
        <template v-if="server">
          <FilterSelect :model-value="status" label="Status" :options="Object.keys(STATUS).map((k) => ({ value: k, label: `${k} (${counts[k] || 0})` }))" @update:model-value="(v) => (status = v || '')" />
        </template>
        <template v-if="zones.length > 1">
          <FilterSelect :model-value="zone" label="Zone" :options="zones" @update:model-value="(v) => (zone = v || '')" />
        </template>
      </div>
      <div class="card flush">
        <div class="table-wrap">
          <table>
            <thead><tr><th>Name</th><th>Type</th><th>Value</th><th>Zone</th><th>Host</th><th v-if="server">Status</th></tr></thead>
            <tbody>
              <tr v-for="r in paged" :key="`${r.name} ${r.type} ${r.value}`">
                <td class="mono small">{{ r.name }}<span v-if="r.public" class="tag" style="margin-left: 6px">public</span></td>
                <td class="mono small">{{ r.type }}</td>
                <td class="mono small val">{{ r.value }}</td>
                <td class="small faint">{{ r.zone }}</td>
                <td class="small"><RouterLink v-if="r.host" :to="`/hosts/${r.host}?tab=dns`">{{ r.host }}</RouterLink><span v-else-if="r.source === 'custom'" class="faint">custom</span></td>
                <td v-if="server" class="small nowrap"><span class="dot" :class="STATUS[r.status]?.[0]"></span>{{ r.status }}</td>
              </tr>
              <tr v-if="!filtered.length"><td :colspan="server ? 6 : 5" class="empty">{{ rows.length ? 'Nothing matches.' : server ? 'This server has no records labdex knows of yet.' : 'No records yet: hosts with an address in a network that’s in DNS get them.' }}</td></tr>
            </tbody>
          </table>
        </div>
      </div>
      <Pager v-model="page" :total="filtered.length" :size="SIZE" />
      <p v-if="!servers.length" class="hint">Add a Technitium integration to compare with what your DNS server holds.</p>
      <p v-else class="hint">Unmanaged records stay as they are; labdex only changes what it made (comment "labdex").</p>
    </template>
  </div>
</template>

<style scoped>
.dot { display: inline-block; width: 8px; height: 8px; border-radius: 50%; background: var(--faint); margin-right: 6px; opacity: .5; }
.dot.ok { background: var(--ok); opacity: 1; } .dot.warn { background: var(--warn, #fbbf24); opacity: 1; }
.val { max-width: 380px; overflow-wrap: anywhere; }
.nowrap { white-space: nowrap; }
</style>
